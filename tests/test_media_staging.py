    async def test_close_waits_for_commit_cancellation_cleanup(self):
        canceled = asyncio.Event()
        allow_cleanup = asyncio.Event()
        cleaned = asyncio.Event()

        async def sender(*args):
            self.host.entered.set()
            try:
                await asyncio.Event().wait()
            except asyncio.CancelledError:
                canceled.set()
                await allow_cleanup.wait()
                cleaned.set()
                raise

        self.host.reply_attachment = sender
        uid = self.begin()['upload_id']
        self.chunk(uid)
        task = asyncio.create_task(self.stager.commit(MID, KEY, uid))
        await self.host.entered.wait()
        self.stager.close()
        drain = asyncio.create_task(self.stager.wait_closed())
        await canceled.wait()
        self.assertFalse(drain.done())
        self.assertFalse(cleaned.is_set())
        allow_cleanup.set()
        await drain
        self.assertTrue(cleaned.is_set())
        self.assertTrue(task.cancelled())
        self.assertFalse(self.stager._commit_tasks)

