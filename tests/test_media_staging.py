class DurableClaimTests(unittest.IsolatedAsyncioTestCase):
    async def test_commit_reuses_host_durable_claim_before_adapter(self):
        with tempfile.TemporaryDirectory() as directory:
            binding = host_module.Binding('qq', 'aiocqhttp', '100', '200')
            store = host_module.Store(Path(directory) / 'inbox.sqlite3', binding)
            mid, _ = store.ingest({'source_id': '123', 'umo': 'qq:private:200', 'text': 'request'})
            calls = []

            async def preflight(row):
                return object()

            async def never_text(*args):
                raise AssertionError('media cannot use ordinary text')

            host = host_module.Host(store, preflight, never_text)

            async def reply_attachment(message_id, kind, filename, value, reply_key):
                payload = media_module.validate_media(kind, filename, value)

                async def send(target, row, fingerprint):
                    claim = store.db.execute('SELECT state,text FROM replies WHERE reply_key=?', (reply_key,)).fetchone()
                    self.assertEqual(claim['state'], 'sending')
                    self.assertEqual(claim['text'], host_module.MEDIA_REPLY_PREFIX + payload.fingerprint)
                    calls.append((message_id, payload.sha256))
                    return True

                return await host.reply(message_id, host_module.MEDIA_REPLY_PREFIX + payload.fingerprint,
                                        reply_key, _send_override=send)

            host.reply_attachment = reply_attachment
            stager = staging.MediaStaging(host, guard=lambda message_id: store.read(message_id))
            try:
                for _ in range(2):
                    # A new staging runtime still reaches the same durable key.
                    data = b'generated bytes'
                    uid = stager.begin(mid, KEY, 'file', 'result.bin', len(data), hashlib.sha256(data).hexdigest())['upload_id']
                    stager.chunk(mid, KEY, uid, 0, encoded(data))
                    self.assertEqual((await stager.commit(mid, KEY, uid))['state'], 'adapter_completed')
                    stager.close()
                    stager = staging.MediaStaging(host, guard=lambda message_id: store.read(message_id))
                self.assertEqual(len(calls), 1)
            finally:
                stager.close()
                await host.close()
                store.close()


