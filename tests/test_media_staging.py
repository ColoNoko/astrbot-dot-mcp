def encoded(data):
    return base64.b64encode(data).decode('ascii')


class FakeHost:
    stopping = False

    def __init__(self):
        self.calls = []
        self.result = {'reply_key': KEY, 'state': 'adapter_completed'}
        self.entered = asyncio.Event()
        self.wait = None
        self.error = None

    async def reply_attachment(self, *args):
        self.calls.append(args)
        self.entered.set()
        if self.wait is not None:
            await self.wait.wait()
        if self.error is not None:
            raise self.error
        return self.result


class StagingTests(unittest.IsolatedAsyncioTestCase):
    def setUp(self):
        self.host = FakeHost()
        self.now = 100.0
        self.allowed = True
        self.guarded = []

        def guard(mid):
            self.guarded.append(mid)
            if not self.allowed:
                raise staging.Rejected('binding_inactive')

        self.stager = staging.MediaStaging(self.host, guard=guard, clock=lambda: self.now)
        self.addCleanup(self.stager.close)

    def begin(self, data=b'hello world', **changes):
        args = {'message_id': MID, 'reply_key': KEY, 'kind': 'file',
                'filename': 'output.bin', 'size_bytes': len(data),
                'sha256': hashlib.sha256(data).hexdigest()}
        args.update(changes)
        return self.stager.begin(**args)

    def chunk(self, upload_id, data=b'hello world', offset=0, **changes):
        args = {'message_id': MID, 'reply_key': KEY, 'upload_id': upload_id,
                'offset': offset, 'data_base64': encoded(data)}
        args.update(changes)
        return self.stager.chunk(**args)

    async def test_begin_chunk_commit_uses_only_bound_original_host_route(self):
        data = b'generated bytes' * 101
        start = self.begin(data, filename='ｏutput.bin')
        uid = start['upload_id']
        self.assertRegex(uid, r'^upl_[a-f0-9]{32}$')
        self.assertEqual(start['limits']['max_size_bytes'], 20_000_000)
        self.assertEqual(start['limits']['max_chunk_bytes'], 262144)
        self.assertEqual(start['limits']['idle_timeout_seconds'], 20)
        self.assertEqual(start['next_offset'], 0)
        self.assertEqual(self.host.calls, [])
        self.chunk(uid, data[:100])
        self.assertEqual(self.host.calls, [])
        result = self.chunk(uid, data[100:], offset=100)
        self.assertEqual(result['next_offset'], len(data))
        self.assertEqual(self.host.calls, [])
        answer = await self.stager.commit(MID, KEY, uid)
        self.assertEqual(answer, self.host.result)
        self.assertEqual(self.host.calls, [(MID, 'file', 'output.bin', encoded(data), KEY)])
        self.assertEqual(self.stager.status()['reserved_bytes'], 0)
        self.assertEqual(await self.stager.commit(MID, KEY, uid), answer)
        self.assertEqual(len(self.host.calls), 1)
        with self.assertRaisesRegex(staging.Rejected, '^media_upload_finished$'):
            self.chunk(uid, data)

    async def test_exact_20mb_boundary_in_77_chunks(self):
        # Only this test materializes 20 MB. It never invokes a QQ adapter.
        data = b'x' * 20_000_000
        uid = self.begin(data)['upload_id']
        count = 0
        for offset in range(0, len(data), staging.MAX_CHUNK_BYTES):
            self.chunk(uid, data[offset:offset + staging.MAX_CHUNK_BYTES], offset)
            self.now += 0.1
            count += 1
        self.assertEqual(count, 77)
        await self.stager.commit(MID, KEY, uid)
        call = self.host.calls[0]
        self.assertEqual(len(base64.b64decode(call[3], validate=True)), 20_000_000)
        self.assertEqual(hashlib.sha256(base64.b64decode(call[3])).hexdigest(), hashlib.sha256(data).hexdigest())
        with self.assertRaisesRegex(staging.Rejected, '^media_too_large$'):
            self.begin(size_bytes=20_000_001, reply_key='other')

