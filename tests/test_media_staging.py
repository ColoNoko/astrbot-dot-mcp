    async def test_revocation_on_every_operation_and_after_chunk_decode(self):
        uid = self.begin()['upload_id']
        self.allowed = False
        for action in (lambda: self.begin(reply_key='other'), lambda: self.chunk(uid),
                       lambda: self.stager.abort(MID, KEY, uid)):
            with self.assertRaisesRegex(staging.Rejected, '^binding_inactive$'):
                action()
        with self.assertRaisesRegex(staging.Rejected, '^binding_inactive$'):
            await self.stager.commit(MID, KEY, uid)
        self.assertEqual(self.stager._uploads[uid].offset, 0)
        self.allowed = True
        decode = staging.base64.b64decode

        def revoke_after_decode(*args, **kwargs):
            data = decode(*args, **kwargs)
            self.allowed = False
            return data

        stream = self.stager._uploads[uid].stream
        with patch.object(staging.base64, 'b64decode', side_effect=revoke_after_decode):
            with self.assertRaisesRegex(staging.Rejected, '^binding_inactive$'):
                self.chunk(uid)
        self.assertTrue(stream.closed)
        self.assertEqual(self.stager._uploads[uid].offset, 0)
        self.assertEqual(self.host.calls, [])

